/**
 * 生成一份示例快照。办公室与老师/事项的互相引用在这里统一推导，
 * 避免手写两份关联表写错。
 */
export function demoPlacesSnapshot(now = new Date().toISOString()): PlacesSnapshot {
  const offices: PlaceOffice[] = officeSeeds.map((seed) => ({
    ...seed,
    serviceIds: demoServices.filter((service) => service.officeId === seed.id).map((s) => s.id),
    teacherIds: demoTeachers.filter((teacher) => teacher.officeId === seed.id).map((t) => t.id),
    source: 'demo',
    verifiedAt: null,
    updatedAt: now,
  }));
  return {
    version: 1,
    generatedAt: now,
    campuses: demoCampuses,
    buildings: demoBuildings,
    departments: demoDepartments,
    offices,
    teachers: demoTeachers,
    services: demoServices,
    corrections: [],
  };
}
